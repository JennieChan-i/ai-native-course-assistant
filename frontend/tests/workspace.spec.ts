import {test,expect} from '@playwright/test'

test('all pages load without console errors; source, filtering and responsive layout work',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'今天想学什么？'})).toBeVisible()
  await page.screenshot({path:'../data/qa-home.png',fullPage:true})
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.getByRole('button',{name:'课程知识库',exact:true}).click()
  await expect(page.getByText('找到 17 条课程切片')).toBeVisible()
  await page.locator('.chunk-row').first().click()
  await expect(page.locator('dialog[open] .source-body')).not.toBeEmpty()
  await page.getByRole('button',{name:'关闭课程原文'}).click()
  await page.getByRole('button',{name:'语义检索实验'}).click()
  await page.getByRole('textbox',{name:'语义检索问题'}).fill('RAG 是什么？')
  await page.getByRole('button',{name:'真实检索'}).click()
  await expect(page.locator('.chunk-row')).toHaveCount(5,{timeout:30000})
  await page.screenshot({path:'../data/qa-retrieval.png',fullPage:true})
  for(const [button,title] of [['运行看板','运行看板'],['调用日志','调用日志'],['反馈与 Badcase','反馈与 Badcase'],['评测中心','检索评测与边界验证']]){
    await page.getByRole('navigation').getByRole('button',{name:button,exact:true}).click()
    await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible()
  }
  await page.getByRole('button',{name:'返回学习助手',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  await page.evaluate(()=>localStorage.setItem('settingsTab','general'))
  await page.reload()
  await expect(page.getByRole('button',{name:'展开导航'})).toBeVisible()
  await page.getByRole('button',{name:'展开导航'}).click()
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.getByRole('button',{name:'展开设置导航'}).click()
  await page.getByRole('navigation').getByRole('button',{name:'课程知识库',exact:true}).click()
  await expect(page.getByRole('heading',{name:'课程知识库',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await expect.poll(()=>page.locator('.settings-sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  await page.screenshot({path:'../data/qa-mobile.png'})
  expect(errors).toEqual([])
})

test('live chat streams real answers; feedback and history survive reload',async({page})=>{
  test.skip(!process.env.RUN_LIVE_TESTS,'Set RUN_LIVE_TESTS=1 and configure the model key for online checks')
  await page.goto('/')
  await page.getByRole('button',{name:'新对话',exact:true}).click()
  await page.getByRole('textbox',{name:'问题或待点评文本'}).fill('RAG 是什么？请用三点回答，并引用课程。')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.locator('.message.assistant .message-actions')).toBeVisible({timeout:100000})
  await expect(page.locator('.message.assistant')).toContainText('RAG')
  await page.getByRole('button',{name:/来源与过程/}).click()
  await expect(page.locator('.evidence')).toContainText('qwen3.8-flash')
  await page.locator('.inline-source').first().click()
  await expect(page.locator('dialog[open] .source-body')).not.toBeEmpty()
  await page.getByRole('button',{name:'关闭课程原文'}).click()
  await page.screenshot({path:'../data/qa-live-chat.png',fullPage:true})
  await page.getByRole('button',{name:'有问题',exact:true}).click()
  await page.getByRole('textbox',{name:'反馈原因'}).fill('面试展示验收：希望增加一个实际产品例子。')
  await page.getByRole('button',{name:'提交反馈',exact:true}).click()
  await expect(page.locator('.feedback-form')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.message.assistant')).toContainText('RAG')
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.getByRole('navigation').getByRole('button',{name:'反馈与 Badcase',exact:true}).click()
  await page.getByRole('button',{name:'实际反馈',exact:true}).click()
  await expect(page.locator('.badcase-row').first()).toContainText('面试展示验收')
  await page.locator('.badcase-row').first().click()
  await page.getByLabel('原因分析').fill('回答基本正确，用户希望更具体。')
  await page.getByLabel('修复说明').fill('下一轮加入课程智能客服例子。')
  await page.getByLabel('复测记录').fill('已确认来源与问答链路可读取；例子补充作为后续优化。')
  await page.getByRole('button',{name:'保存处理记录'}).click()
  await expect(page.locator('.badcase-editor')).toHaveCount(0)
})
